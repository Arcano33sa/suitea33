'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'analitica/script.js'), 'utf8');
let now = '2026-11-15T12:00:00';
class Clock extends Date { constructor(...args){ super(...(args.length ? args : [now])); } }
const sandbox = { Date:Clock, console, document:{addEventListener(){},getElementById(){return null;}}, window:{addEventListener(){}}, MutationObserver:class{observe(){}} };
vm.createContext(sandbox);
vm.runInContext(source.replace(/\}\)\(\);\s*$/, 'this.seed = (rows, merma) => {sales = rows; mermaRows = merma; events = [{id:1,name:"Catálogo"}];}; this.api = {resolvePeriodRange, saleInRange, analyticsRangeLabel, getCurrentRange, analyticsEventMatches, analyticsEventOptions, selectedMermaAnalytics};\n})();'), sandbox);
const {resolvePeriodRange:range, saleInRange:includes, analyticsRangeLabel:label} = sandbox.api;
assert.equal(label(range('mtd')), '2026-11-01 → 2026-11-15');
assert.equal(label(sandbox.api.getCurrentRange()), '2026-11-01 → 2026-11-15');
assert.equal(includes({date:'2026-10-31'},range('mtd')), false);
assert.equal(includes({date:'2026-11-01'},range('mtd')), true);
assert.equal(includes({date:'2026-11-15'},range('mtd')), true);
assert.equal(includes({date:'2026-11-16'},range('mtd')), false);
assert.equal(label(range('previous-month')), '2026-10-01 → 2026-10-31');
assert.equal(label(range('30d')), '2026-10-17 → 2026-11-15');
now = '2026-01-01T12:00:00';
assert.equal(label(range('previous-month')), '2025-12-01 → 2025-12-31');
assert.equal(label(range('mtd')), '2026-01-01 → 2026-01-01');
now = '2024-03-15T12:00:00';
assert.equal(label(range('previous-month')), '2024-02-01 → 2024-02-29');
assert.equal(range('previous-month').to.getMilliseconds(),999);
now = '2025-03-15T12:00:00';
assert.equal(label(range('previous-month')), '2025-02-01 → 2025-02-28');
assert.equal(label(range('all')), 'Todo el histórico');
assert.equal(label(range('custom','2026-10-02','2026-10-05')), '2026-10-02 → 2026-10-05');
const fixture = [{eventId:1,eventName:'Viejo'}, {eventId:'1'}, {eventId:'2',eventName:'Histórico'}, {}, {eventId:null}, {eventId:0}];
const merma = [{eventId:3,eventName:'Solo merma',date:'2026-10-15',isFinalEventMerma:true,costoMermaFinal:7}];
const before = JSON.stringify([fixture,merma]);
sandbox.seed(fixture,merma);
const api = sandbox.api;
assert.equal(fixture.filter(row=>api.analyticsEventMatches(row,'1')).length,2);
assert.equal(fixture.filter(row=>api.analyticsEventMatches(row,'sin-evento')).length,2);
assert.equal(fixture.filter(row=>api.analyticsEventMatches(row,'0')).length,1);
assert.equal(fixture.filter(row=>api.analyticsEventMatches(row,'all')).length,6);
const options = api.analyticsEventOptions();
assert.equal(options.filter(([id])=>id==='1').length,1);
assert.ok(options.find(([id,name])=>id==='2' && name.includes('Histórico')));
assert.ok(options.find(([id])=>id==='3'));
const selected = {from:new Date(2026,9,1),to:new Date(2026,9,31),eventFilter:'3'};
assert.equal(api.selectedMermaAnalytics(selected).length,1);
assert.equal(api.selectedMermaAnalytics({...selected,eventFilter:'1'}).length,0);
assert.equal(includes({date:'2026-10-15',eventId:'3'},selected),true);
assert.equal(includes({date:'2026-11-01',eventId:3},selected),false);
assert.equal(JSON.stringify([fixture,merma]),before);
console.log('APROBADA E2 VM: IDs numéricos/texto/cero, General, catálogo, históricos, merma sin ventas y fechas combinadas; datos intactos.');
